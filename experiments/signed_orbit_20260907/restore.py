"""Restore recorded text evidence; binary arrays are regenerated and hash-checked."""
from __future__ import annotations
import argparse
import base64
import hashlib
import json
import lzma
from pathlib import Path

SHA256 = 'de85f7342d50bde12ee2de39515e8b60f9c0a455eb9e10c8445ad42f43f21257'

def load() -> dict[str, str]:
    here = Path(__file__).resolve().parent
    text = ''.join((here / f'evidence.{i}.b64').read_text().strip() for i in range(6))
    payload = base64.b64decode(text, validate=True)
    if hashlib.sha256(payload).hexdigest() != SHA256:
        raise ValueError('Evidence capsule checksum mismatch')
    files = json.loads(lzma.decompress(payload).decode('utf-8'))
    if not isinstance(files, dict) or len(files) != 34:
        raise ValueError('Unexpected evidence index')
    return files

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path)
    parser.add_argument('--verify', type=Path, help='Regenerated parent containing run/ and followon/')
    args = parser.parse_args()
    if args.out is None and args.verify is None:
        parser.error('Use --out and/or --verify')
    files = load()
    if args.out is not None:
        out = args.out.resolve()
        for name, text in files.items():
            rel = Path(name)
            if rel.is_absolute() or '..' in rel.parts or not isinstance(text, str):
                raise ValueError(f'Unsafe evidence path: {name}')
            path = (out / rel).resolve()
            if out not in path.parents:
                raise ValueError('Path escapes output directory')
            data = text.encode('utf-8')
            if path.exists() and path.read_bytes() != data:
                raise FileExistsError(f'Refusing to replace different file: {path}')
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        print(f'Restored {len(files)} exact text files; binary arrays require regeneration.')
    if args.verify is not None:
        count = 0
        for part in ('run', 'followon'):
            recorded = files[f'results/{part}/manifest.json'].encode('utf-8')
            base = args.verify / part
            if (base / 'manifest.json').read_bytes() != recorded:
                raise ValueError(f'{part}: manifest differs')
            for name, digest in json.loads(recorded).items():
                if hashlib.sha256((base / name).read_bytes()).hexdigest() != digest:
                    raise ValueError(f'{part}/{name}: regenerated bytes differ')
                count += 1
        print(f'Verified {count} generated files and both original manifests.')

if __name__ == '__main__':
    main()
