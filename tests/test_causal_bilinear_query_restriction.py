def _gf2_rank(words: list[int] | tuple[int, ...]) -> int:
    pivots: dict[int, int] = {}
    for word in words:
        current = word
        while current:
            pivot = current.bit_length() - 1
            if pivot not in pivots:
                pivots[pivot] = current
                break
            current ^= pivots[pivot]
    return len(pivots)


def _span(basis: tuple[int, ...]) -> set[int]:
    values = {0}
    for row in basis:
        values |= {value ^ row for value in tuple(values)}
    return values


def _outer_word(left: int, right: int, rows: int, columns: int) -> int:
    word = 0
    for row in range(rows):
        for column in range(columns):
            if ((left >> row) & 1) and ((right >> column) & 1):
                word |= 1 << (row * columns + column)
    return word


