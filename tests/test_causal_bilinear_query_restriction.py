def test_rank_forces_misses_for_every_best_posthoc_subspace() -> None:
    # Exhaust all subspaces generated by up to two vectors in F_2^4 and all
    # populations of four distinct vectors.  The number of population vectors
    # outside any B-dimensional subspace is always at least rank-B.
    ambient = tuple(range(1 << 4))
    for first, second in itertools.product(ambient, repeat=2):
        subspace = _span((first, second))
        dimension = _gf2_rank((first, second))
        for population in itertools.combinations(ambient, 4):
            rank = _gf2_rank(population)
            misses = sum(word not in subspace for word in population)
            assert misses >= span_miss_lower_bound(rank, 4, dimension)


def test_outer_product_population_can_reach_full_observed_rank() -> None:
    tensors = [
        _outer_word(0b01, 0b01, 2, 2),
        _outer_word(0b01, 0b10, 2, 2),
        _outer_word(0b10, 0b01, 2, 2),
        _outer_word(0b10, 0b10, 2, 2),
    ]
    assert _gf2_rank(tensors) == 4
    assert span_miss_lower_bound(4, 4, 2) == 2


def test_dependent_outer_products_receive_no_false_rank_credit() -> None:
    first = _outer_word(0b11, 0b01, 2, 2)
    duplicate = _outer_word(0b11, 0b01, 2, 2)
    zero = _outer_word(0b00, 0b11, 2, 2)
    assert _gf2_rank([first, duplicate, zero]) == 1
    assert span_miss_lower_bound(1, 3, 1) == 0


def test_last_down_weighted_fallback_threshold_is_four_rows() -> None:
    dimension = largest_scannable_span_dimension()
    common = traffic_fraction_before_fallback(dimension)
    allowed = maximum_weighted_fallback_misses(
        population_size=EVALUATION_QUERY_COUNT,
        matrix_coefficients=one_down_projection_coefficients(),
        common_fraction=common,
    )
    assert allowed == 4
    assert minimum_rejecting_rank(
        population_size=EVALUATION_QUERY_COUNT,
        span_dimension=dimension,
        allowed_misses=allowed,
    ) == 28


